package gg.vape.ui.font.stb;

public class StbTrueTypeCharStringContext {
   public int Z;
   public int c;
   public int q;
   public float p;
   public int v;
   public float o;
   public float s;
   public float C;
   public int J;
   public int y;
   public int f;
   public StbTrueTypeVertex[] V;

   public StbTrueTypeCharStringContext(int n) {
      this.J = n;
      this.v = 0;
      this.s = 0.0F;
      this.p = 0.0F;
      this.C = 0.0F;
      this.o = 0.0F;
      this.y = 0;
      this.c = 0;
      this.Z = 0;
      this.f = 0;
      this.V = null;
      this.q = 0;
   }
}
